    /// <summary>
    /// In-game hero colours per origin. The hero is drawn with PowerHoof/SpritePaletted: every atlas colour is looked
    /// up in the material's 256x64 "_ColorRamp" (slot x = r*16 + 16*(g*16), y = b*64; pink = keep the atlas colour).
    /// Each player owns one ramp texture (PlayerSetup.m_heroMaterial: PaletteBlue/Red/Green/Yellow), shared by every
    /// hero body that player ever gets, the clipping variant and the menus that show their hero, and it already maps
    /// the tunic/vest/shadow slots to the player's colour. An origin overwrites those slots with its own scheme.
    ///
    /// Writes are idempotent and reversible: the vanilla ramp is snapshotted once, slots this class wrote are restored
    /// before a new scheme goes on (no scheme = vanilla ramp), and only pixels that differ are written, then Apply()d.
    /// It runs on events only (origin/deity set, hero init, weapon colour swaps, status colour unswaps): nothing per
    /// frame. Neighbour slots are filled like ColorSwapper does (GPU rounding at slot edges) but never on a slot any
    /// hero-atlas colour uses, so weapons, blood, skin and hilts can't pick up an origin colour by accident.
    /// </summary>
    public static class HeroLooks
    {
        const string RAMP = "_ColorRamp";
        const int RampW = 256, RampH = 64;

