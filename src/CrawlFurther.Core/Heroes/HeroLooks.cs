        /// <summary>Per origin id + "#" + player slot 0-3: the colour swaps of that origin's hero in that player's colours
        /// (set with <see cref="SetColours"/>). An origin without them wears the vanilla player colours.</summary>
        public static readonly Dictionary<string, ColorSwap[]> Tables = new Dictionary<string, ColorSwap[]>();
        /// <summary>Per weapon prefab name ("ModWeapon" + id): in-hand colours of the equipped mod weapon. Composed with the
        /// origin's scheme into one plan; the origin wins a slot both write.</summary>
        public static readonly Dictionary<string, ColorSwap[]> WeaponTables = new Dictionary<string, ColorSwap[]>();
        static readonly bool[] s_isHeroSlot = new bool[RampW * RampH];

        static HeroLooks()
        {
            foreach (var s in s_heroSlots) if (s < s_isHeroSlot.Length) s_isHeroSlot[s] = true;
        }

        /// <summary>
        /// Set an origin's hero colours for one player slot (0-3, the player colours blue, red, green, yellow).
        /// <paramref name="fromTo"/> holds pairs of 0xRRGGBB colours: a colour of the vanilla hero atlas (AtlasHero),
        /// then the colour it becomes. tools/sprites/hero_looks.py builds these tables and previews them.
        /// </summary>
        public static void SetColours(string originId, int playerSlot, params int[] fromTo)
        {
            var sw = new ColorSwap[fromTo.Length / 2];
            for (int i = 0; i < sw.Length; i++)
                sw[i] = new ColorSwap { m_from = Rgb(fromTo[2 * i]), m_to = Rgb(fromTo[2 * i + 1]) };
            Tables[originId + "#" + playerSlot] = sw;
        }

        static Color Rgb(int v)
        {
            return new Color32((byte)(v >> 16), (byte)(v >> 8), (byte)v, 255);
        }

        /// <summary>The ramp slot ColorSwapper.Swap writes for a source colour (same maths, as an x + 256*y index).</summary>
        public static int Slot(Color c)
        {
            int x = Mathf.Min(15, Mathf.FloorToInt(c.r * 16f)) + Mathf.Min(15, Mathf.FloorToInt(c.g * 16f)) * 16;
            int y = Mathf.Min(RampH - 1, Mathf.FloorToInt(c.b * RampH));
            return Mathf.Clamp(x, 0, RampW - 1) + RampW * Mathf.Clamp(y, 0, RampH - 1);
        }

        sealed class Plan
        {
            public int[] idx;
            public Color32[] col;
        }

        sealed class Ramp
        {
            public Texture2D tex;
            public Color32[] orig;              // the vanilla ramp, snapshotted on first touch
            public int[] stamp;                 // scratch marks for "slot is in the new plan"
            public int gen;
            public int[] touched = new int[0];  // slots currently holding our colours
            public readonly Dictionary<string, Plan> plans = new Dictionary<string, Plan>();
            public bool broken;
        }

        static readonly Dictionary<Texture2D, Ramp> s_ramps = new Dictionary<Texture2D, Ramp>();
        static readonly HashSet<int> s_logged = new HashSet<int>();
        static bool s_errorLogged, s_sizeLogged;

        /// <summary>Put the player's origin colours on their hero ramp (or the vanilla ones for an origin without a scheme).</summary>
        public static void Refresh(PlayerData pd)
        {
            HeroGear.Version++;     // the same events (deity / origin set, new hero body, colour swaps) change the worn gear
            try { RefreshInner(pd); }
            catch (Exception e)
            {
                if (s_errorLogged) return;
                s_errorLogged = true;
                FurtherCore.Log.LogError("HeroLooks: refresh failed (further errors muted): " + e);
            }
        }

        static void RefreshInner(PlayerData pd)
        {
            if (pd == null) return;
            var setup = pd.Setup;
            var mat = setup != null ? setup.m_heroMaterial : null;
            if (mat == null || !mat.HasProperty(RAMP)) return;
            var tex = mat.GetTexture(RAMP) as Texture2D;
            if (tex == null) return;
            if (tex.width != RampW || tex.height != RampH)
            {
                if (!s_sizeLogged) { s_sizeLogged = true; FurtherCore.Log.LogWarning("HeroLooks: unexpected ramp size " + tex.width + "x" + tex.height + " on " + tex.name); }
                return;
            }
            var r = GetRamp(tex);
            if (r == null) return;

            var def = HeroClasses.For(pd);
            string id = def != null ? def.id : null;
            string wkey = WeaponKey(pd);
            string okey;
            var os = OriginSwaps(pd, def, out okey);
            var plan = GetPlan(r, okey, os, wkey);

            int changed = 0;
            r.gen++;
            if (plan != null) for (int i = 0; i < plan.idx.Length; i++) r.stamp[plan.idx[i]] = r.gen;
            // slots the previous scheme wrote and this one doesn't: back to the player's vanilla colour
            for (int i = 0; i < r.touched.Length; i++)
            {
                int s = r.touched[i];
                if (r.stamp[s] != r.gen) changed += Put(tex, s, r.orig[s]);
            }
            if (plan != null) for (int i = 0; i < plan.idx.Length; i++) changed += Put(tex, plan.idx[i], plan.col[i]);
            r.touched = plan != null ? plan.idx : s_none;
            if (changed > 0) { tex.Apply(); CompatOnline.TextureChanged(tex); }   // online clients get the new ramp

            int key = (pd.Id * 1000 + HeroClasses.All.IndexOf(def)) * 31 + ((okey ?? "").GetHashCode() & 0xfff) + (wkey != null ? wkey.GetHashCode() & 0xffff : 0);
            if (s_logged.Add(key))
                FurtherCore.Log.LogInfo("HeroLooks: player " + pd.Id + " origin " + (okey ?? id ?? "?") + (wkey != null ? " weapon " + wkey : "") + " -> "
                                   + (plan != null ? plan.idx.Length : 0) + " ramp slots on " + tex.name + " (" + changed + " written)");
        }

        static readonly int[] s_none = new int[0];

        static int Put(Texture2D tex, int s, Color32 c)
        {
            int x = s % RampW, y = s / RampW;
            var cur = tex.GetPixel(x, y);
            if (Mathf.Abs(cur.r * 255f - c.r) < 0.5f && Mathf.Abs(cur.g * 255f - c.g) < 0.5f && Mathf.Abs(cur.b * 255f - c.b) < 0.5f)
                return 0;
            tex.SetPixel(x, y, c);
            return 1;
        }

        static Ramp GetRamp(Texture2D tex)
        {
            Ramp r;
            if (s_ramps.TryGetValue(tex, out r)) return r.broken ? null : r;
            r = new Ramp { tex = tex };
            s_ramps[tex] = r;
            try
            {
                r.orig = tex.GetPixels32();
                r.stamp = new int[RampW * RampH];
                if (r.orig == null || r.orig.Length != RampW * RampH) throw new Exception("ramp has " + (r.orig == null ? 0 : r.orig.Length) + " pixels");
            }
            catch (Exception e)
            {
                r.broken = true;
                FurtherCore.Log.LogWarning("HeroLooks: can't read hero ramp " + tex.name + ", origin colours disabled for it: " + e.Message);
                return null;
            }
            return r;
        }

        static bool IsPink(Color32 c) { return c.r == 255 && c.g == 0 && c.b == 255; }

        /// <summary>The equipped weapon's key in WeaponTables, or null for a vanilla weapon / no weapon.</summary>
        static string WeaponKey(PlayerData pd)
        {
            var gd = pd.GameData;
            var wd = gd != null ? gd.GetWeaponData() : null;
            var w = wd != null ? wd.m_weapon : null;
            if (w == null) return null;
            string n = w.gameObject.name;
            return WeaponTables.ContainsKey(n) ? n : null;
        }

        /// <summary>Player slot 0-3 whose colours a player's hero wears: read from the hero ramp the player actually draws
        /// with (PaletteBlue/Red/Green/Yellow = P1-P4), so the colours always match the vanilla player colour; falls back
        /// to the player id. The menus use the same slot for the portraits.</summary>
        public static int SlotOf(PlayerData pd)
        {
            if (pd == null) return 0;
            try
            {
                var setup = pd.Setup;
                var mat = setup != null ? setup.m_heroMaterial : null;
                var tex = mat != null && mat.HasProperty(RAMP) ? mat.GetTexture(RAMP) : null;
                string n = tex != null ? tex.name ?? "" : "";
                if (n.IndexOf("Blue", StringComparison.OrdinalIgnoreCase) >= 0) return 0;
                if (n.IndexOf("Red", StringComparison.OrdinalIgnoreCase) >= 0) return 1;
                if (n.IndexOf("Green", StringComparison.OrdinalIgnoreCase) >= 0) return 2;
                if (n.IndexOf("Yellow", StringComparison.OrdinalIgnoreCase) >= 0) return 3;
            }
            catch { }
            return SlotOfId(pd.Id);
        }

        /// <summary>True if origin <paramref name="id"/> has colours for player slot 0-3.</summary>
        public static bool HasSlotTable(string id, int slot) { return Tables.ContainsKey(id + "#" + slot); }

        /// <summary>Slot for a player id when only the id is known (menus before a PlayerData exists).</summary>
        public static int SlotOfId(int playerId)
        {
            var pd = playerId >= 0 ? SystemPlayers.GetPlayer(playerId) : null;
            if (pd != null && pd.Setup != null && pd.Setup.m_heroMaterial != null)
            {
                var tex = pd.Setup.m_heroMaterial.HasProperty(RAMP) ? pd.Setup.m_heroMaterial.GetTexture(RAMP) : null;
                if (tex != null && !string.IsNullOrEmpty(tex.name))
                {
                    string n = tex.name;
                    if (n.IndexOf("Blue", StringComparison.OrdinalIgnoreCase) >= 0) return 0;
                    if (n.IndexOf("Red", StringComparison.OrdinalIgnoreCase) >= 0) return 1;
                    if (n.IndexOf("Green", StringComparison.OrdinalIgnoreCase) >= 0) return 2;
                    if (n.IndexOf("Yellow", StringComparison.OrdinalIgnoreCase) >= 0) return 3;
                }
            }
            return ((playerId % 4) + 4) % 4;
        }

        /// <summary>The origin part of the scheme for this player: the per-slot table of a normal origin, or a silver /
        /// gold hero's swaps. key identifies the scheme for the plan cache.</summary>
        static ColorSwap[] OriginSwaps(PlayerData pd, OriginDef def, out string key)
        {
            key = null;
            if (def == null) return null;
            if (def.tier != SlotTier.Normal) return HeroClasses.CustomHeroes != null ? HeroClasses.CustomHeroes.BodySwaps(pd, def.tier, out key) : null;
            ColorSwap[] os;
            string k = def.id + "#" + SlotOf(pd);
            if (Tables.TryGetValue(k, out os)) { key = k; return os; }
            return null;
        }

        /// <summary>The slots and colours one origin scheme + mod weapon writes on one ramp (built once per ramp and pair).</summary>
        static Plan GetPlan(Ramp r, string id, ColorSwap[] os, string wkey)
        {
            ColorSwap[] ws = null;
            if (wkey != null) WeaponTables.TryGetValue(wkey, out ws);
            if ((os == null || os.Length == 0) && (ws == null || ws.Length == 0)) return null;
            string pkey = (id ?? "") + "|" + (wkey ?? "");
            Plan p;
            if (r.plans.TryGetValue(pkey, out p)) return p;
            var sw = new List<ColorSwap>();
            if (ws != null) sw.AddRange(ws);
            if (os != null) sw.AddRange(os);                  // origin last: it wins a slot both write
            var pos = new Dictionary<int, int>();
            var idx = new List<int>();
            var col = new List<Color32>();
            // exact slots: a later entry for the same slot wins, like consecutive Swap() calls
            foreach (var s in sw)
            {
                if (s == null) continue;
                int k = Slot(s.m_from);
                Color32 c = s.m_to;
                int at;
                if (pos.TryGetValue(k, out at)) col[at] = c;
                else { pos[k] = idx.Count; idx.Add(k); col.Add(c); }
            }
            // neighbour fills (ColorSwapper's rule), only on slots that are pink in the vanilla ramp and unused by the hero atlas
            foreach (var s in sw)
            {
                if (s == null) continue;
                int k = Slot(s.m_from);
                int x = k % RampW, y = k / RampW;
                Color32 c = col[pos[k]];
                for (int n = 0; n < 8; n++)
                {
                    int nx = x + NX[n], ny = y + NY[n];
                    if (nx < 0 || ny < 0 || nx >= RampW || ny >= RampH) continue;
                    int nk = nx + RampW * ny;
                    if (pos.ContainsKey(nk) || s_isHeroSlot[nk] || !IsPink(r.orig[nk])) continue;
                    pos[nk] = idx.Count; idx.Add(nk); col.Add(c);
                }
            }
            p = new Plan { idx = idx.ToArray(), col = col.ToArray() };
            r.plans[pkey] = p;
            return p;
        }

        static readonly int[] NX = { -1, 1, -1, 1, -1, 1, 0, 0 };
        static readonly int[] NY = { 0, 0, 1, 1, -1, -1, 1, -1 };
    }


    /// <summary>The origin is (re)applied after every SetDeity (god pick, origin picker preview, run start).</summary>
    [HarmonyPatch(typeof(PlayerData), "SetDeity", new[] { typeof(Deity) })]
    static class Patch_HeroLooksSetDeity
    {
        static void Postfix(PlayerData __instance) { HeroLooks.Refresh(__instance); }
    }

    /// <summary>A body becomes this player's hero: the hero material (and its ramp) was just assigned.</summary>
    [HarmonyPatch(typeof(Player), "InitAsPlayer")]
    static class Patch_HeroLooksInitAsPlayer
    {
        static void Postfix(PlayerData playerData, bool ___m_isHero)
        {
            if (___m_isHero && playerData != null) HeroLooks.Refresh(playerData);
        }
    }

    /// <summary>Weapon combo / magic / status colour swaps write the same ramp; ours go back on after them. The prefix
    /// runs the plan for the weapon just equipped first, so a previous mod weapon's slots are restored before a vanilla
    /// weapon's own swaps go on (restoring after would wipe a vanilla magic weapon's colours on a shared slot).</summary>
    [HarmonyPatch(typeof(Player), "ApplyColorSwap")]
    static class Patch_HeroLooksApplyColorSwap
    {
        static void Prefix(PlayerData ___m_playerData, bool ___m_isHero)
        {
            if (___m_isHero && ___m_playerData != null) HeroLooks.Refresh(___m_playerData);
        }

        static void Postfix(PlayerData ___m_playerData, bool ___m_isHero)
        {
            if (___m_isHero && ___m_playerData != null) HeroLooks.Refresh(___m_playerData);
        }
    }

    /// <summary>UnSwap writes pink (= no swap) into the slot: if it was one of ours, put it back.</summary>
    [HarmonyPatch(typeof(Player), "RemoveColorSwaps")]
    static class Patch_HeroLooksRemoveColorSwaps
    {
        static void Postfix(PlayerData ___m_playerData, bool ___m_isHero)
        {
            if (___m_isHero && ___m_playerData != null) HeroLooks.Refresh(___m_playerData);
        }
    }

    [HarmonyPatch(typeof(PlayerStatusManager), "RemoveStatus", new[] { typeof(ActiveStatus) })]
    static class Patch_HeroLooksRemoveStatus
    {
        static void Postfix(ActiveStatus activeStatus, PlayerData ___m_playerData)
        {
            if (activeStatus == null || activeStatus.m_data == null || ___m_playerData == null || !___m_playerData.IsHero) return;
            var cs = activeStatus.m_data.m_colorSwap;
            if (cs != null && cs.Length > 0) HeroLooks.Refresh(___m_playerData);
        }
    }
