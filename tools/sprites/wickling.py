LEGSPLIT = 4   # pixels at y >= -LEGSPLIT (from feet) count as legs


def legs(x, y, c): return y >= -LEGSPLIT
def body(x, y, c): return y < -LEGSPLIT


def build(outdir):
    base = Spr.parse(IDLE, feet_x=8)
    strike = Spr.parse(STRIKE, feet_x=7)

    idle = [base]
    # run: 3 frames (matches base kit). legs scissor, body bobs.
    run = []
    for i, (lx, by) in enumerate([(1, -1), (0, 0), (-1, -1)]):
        s = base.region_shift(lambda x, y, c: legs(x, y, c) and x < 0, lx, 0)
        s = s.region_shift(lambda x, y, c: legs(x, y, c) and x >= 0, -lx, 0)
        s = s.region_shift(body, 0, by)
        run.append(s.flame_flicker(i + 1).shear(0.08 * (1 if by else 0), y_pivot=-LEGSPLIT, pred=body))
    # attack (4 frames): crouch back -> lunge -> hold -> recover
    windup = base.shift(-1, 0).squash(0.9).shear(-0.1, y_pivot=0)
    attack = [windup, strike.shift(2, 0), strike.shift(3, 0).flame_flicker(1), base.shift(1, 0)]
    # special (rolling fireball): rear up, flame flares huge, then spits
    special = [base.shift(-1, 0).flare(1), base.shear(-0.12, y_pivot=0).flare(3), strike.shift(1, 0).flare(2)]
    dead = [base.snuff().rotate_down()]
    statue = [base.stone()]
    knock = [base.shear(-0.15, y_pivot=0).shift(-1, 0)]
    portrait = [base]

    anims = [
        ("Idle", idle, None), ("Run", run, None), ("Dead", dead, None), ("Statue", statue, None),
        ("Knockback", knock, [0.2]), ("Attack0", attack, None), ("Special", special, None),
        ("Portrait", portrait, [0.2]),
    ]
    # base kit cell: 41x28 with feet at row 14 (centre). Our art is taller, so we grow the cell
    # symmetrically and keep the feet on the cell centre line.
    img, man = pack("Wickling", anims, cell_w=44, cell_h=36, feet=(22, 34), outdir=outdir)
    preview(img, man, os.path.join(outdir, "Wickling_preview.png"))
    return img, man


if __name__ == "__main__":
    build(sys.argv[1] if len(sys.argv) > 1 else "out")
