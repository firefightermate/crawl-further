"""Each mod monster's vault challenge goal, from the challenge model and the base game's goals.

    python3 tools/challenge_goals.py            # writes src/CrawlFurther/Monsters/ChallengeGoalsGenerated.cs
    python3 tools/challenge_goals.py --check    # prints the table, writes nothing

The ask (firefightermate, 2026-11-11): "Tier 2 and 3 monsters should be able to reach around the same point as base
monsters, some being stronger, some weaker. Give each monster a goal based on their simulation performances and base
game data. Make them a littleeeee stronger than base game though."

How a goal is set:
  1. Each monster's strength: health x damage rate (basic attack and special) from its kit, with the in-game tier
     numbers (TIER below, the same as ContentSetup) applied: tools/challenge_model/power.py over build/chal/mod.json
     (refresh it with tools/challenge_model/modx.py after changing a monster).
  2. Its simulated score: an expert's median hero level with that strength (challenge_sim.py, calibrated so the game's
     own monsters' median strength scores the game's own average goal at each cost). That is how the game's goals
     relate to its monsters.
  3. Checked against the game's own 59 challenges, the model gets each tier's average goal right but not which monster
     of a tier is harder (its per-monster guess is off by about 2 levels, uncorrelated within a tier): the game's
     designers judged things the numbers here don't see. So each monster's goal is its tier's goal moved half way
     towards its own simulated score, and kept inside the range the game's own goals use for that tier.
"""
import os
import statistics as st
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, "challenge_model"))
import challenge_sim as CS  # noqa: E402
import power as PW          # noqa: E402

OUT = os.path.join(ROOT, "src", "CrawlFurther", "Monsters", "ChallengeGoalsGenerated.cs")

# The in-game tier numbers (ContentSetup / TierRules): starters at least 4 health and hits x1.62, tier 2 health x1.14
# and hits x1.13, finals unchanged. With them each tier's median is about 1.08 of the game's own tier.
STARTER_MIN_HEALTH, STARTER_DAMAGE = 4.0, 1.62
TIER = {0: (1.0, STARTER_DAMAGE), 2.5: (1.14, 1.13), 4: (1.0, 1.0)}

# The game's own goals by cost (all 61 challenges): average, lowest and highest
def game_goals(cost):
    g = [goal for c, goal in CS.GAME_CHALLENGES if (c == 0 if cost == 0 else 2 <= c < 4 if cost == 2.5 else c >= 4)]
    return st.mean(g), min(g), max(g)

SHRINK = 0.5        # how far a goal moves from its tier's towards the monster's own simulated score


def cost_key(c):
    return 0 if c < 1 else 2.5 if c < 4 else 4


def strength(x, m):
    """Health x damage rate in game, from power.py's row x and the def m."""
    key = cost_key(m["evolveCost"])
    hm, dm = TIER[key]
    hp = x["hp"]
    if key == 0:
        hp = max(hp, STARTER_MIN_HEALTH)
    return hp * hm * (x["basic"] + x["sp"]) * dm


def expert_score(power, windup, seed):
    return st.mean(CS.scores(power, windup, n=1500, seed=seed)) - 0.5   # mean: smooth where the median jumps a level


def goals():
    defs = {m["id"]: m for m in PW.M}
    rows = []
    for x in PW.mod_rows():
        m = defs[x["name"]]
        if m["evolveCost"] is None or x["hp"] <= 0:
            continue                       # minions, blobs: no challenge
        key = cost_key(m["evolveCost"])
        rows.append((x, m, key, strength(x, m)))
    vanilla = {0: 3.12, 2.5: 5.59, 4: 10.36}          # the game's own tier medians, same measure (challenge_sim.VANILLA)
    out, summary = [], {}
    for key in (0, 2.5, 4):
        R = [r for r in rows if r[2] == key]
        med = st.median(r[3] for r in R)
        wmed = st.median(r[0]["windup"] for r in R)
        mean, lo, hi = game_goals(key)
        centre = expert_score(CS.K[key] * med, wmed, 7)      # the tier's median monster
        # the tier's goal: the game's own average, plus what the extra strength is worth
        tier_goal = mean + (centre - expert_score(CS.K[key] * vanilla[key], wmed, 7))
        summary[key] = (len(R), med / vanilla[key], mean, tier_goal, lo, hi)
        for i, (x, m, _, p) in enumerate(R):
            own = expert_score(CS.K[key] * p, x["windup"], 100 + i)
            g = tier_goal + SHRINK * (own - centre)
            g = int(round(min(hi, max(lo, g))))
            out.append(dict(id=m["id"], god=x.get("god"), key=key, rel=p / med, own=own, goal=g))
    return out, summary


def write(out):
    lines = [
        "// Generated by tools/challenge_goals.py from the challenge model (tools/challenge_sim.py) and the kits.",
        "// Do not edit by hand: change a monster, refresh build/chal/mod.json (tools/challenge_model/modx.py) and run it again.",
        "using System.Collections.Generic;",
        "",
        "namespace CrawlFurther.Content.Monsters",
        "{",
        "    static class ChallengeGoalsGenerated",
        "    {",
        "        /// <summary>Vault challenge goal (hero level to reach) by monster id.</summary>",
        "        internal static readonly Dictionary<string, int> Goals = new Dictionary<string, int>",
        "        {",
    ]
    for o in sorted(out, key=lambda o: o["id"]):
        lines.append('            { "%s", %d },' % (o["id"], o["goal"]))
    lines += ["        };", "    }", "}", ""]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w").write("\n".join(lines))


if __name__ == "__main__":
    out, summary = goals()
    names = {0: "Starters", 2.5: "Tier 2", 4: "Finals"}
    for key, (n, rel, mean, tg, lo, hi) in summary.items():
        ks = [o["goal"] for o in out if o["key"] == key]
        dist = sorted({g: ks.count(g) for g in ks}.items())
        print("%-8s %3d monsters, median %.2f of the game's own; game's goals avg %.1f (%d-%d); ours avg %.1f %s" % (
            names[key], n, rel, mean, lo, hi, st.mean(ks), dist))
    if "--check" in sys.argv:
        for o in sorted(out, key=lambda o: (o["key"], o["goal"], o["id"])):
            print("  %-4s %-24s strength x%.2f of the tier median, sim %4.1f -> goal %d" % (
                o["key"], o["id"], o["rel"], o["own"], o["goal"]))
    else:
        write(out)
        print("wrote", os.path.relpath(OUT, ROOT), len(out), "goals")
